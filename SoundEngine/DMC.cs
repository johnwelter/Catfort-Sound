        public DMC()
        {
            //due to engine limitations, we can only hold 8 samples in memory at a time - shoose wisely!
            SampleList.Add(EB0_Snare);
            SampleList.Add(EB0_Kick);
            SampleList.Add(SMB3_A);
            SampleList.Add(SMB3_B);
            SampleList.Add(SMB3_C);
            SampleList.Add(SMB3_D);
            SampleList.Add(SMB3_E);
            SampleList.Add(SMB3_H);
        }
        public virtual void SetSample(int sample, int pitch)
        {
            //m_pitch = pitch;
            //Effects.ResetEffects();
            //timer = 0;
            byteIndex = 0;
            bitIndex = 0;
            LoadedSample = sample;
            m_samplePitch = pitch;
            CurrentSample = 0;
            CurrentRawSample = 63;
        }

        public override float GenerateSample()
        {
            if(byteIndex != -1 && LoadedSample != -1)
            {
                Clock(APUConstants.CPU_CLOCKS_PER_SAMPLE, timerLut[m_samplePitch]);
            }
            return CurrentSample;
        }

        public override void UpdateCurrentSample(int updateTicks)
        {
            if(updateTicks == 0)
            {
                return;
            }

            byte[] dmc = SampleList[(int)LoadedSample];

            int step = ((dmc[byteIndex] >> bitIndex) & 1) == 1 ? 2 : -2;

            bitIndex += updateTicks;
            if (bitIndex >= 8)
            {
                bitIndex %= 8;
                byteIndex++;
                if (byteIndex >= dmc.Length)
                {
                    byteIndex = -1;
                }
            }

            float NewSample = CurrentSample + step;
            CurrentRawSample = (NewSample < 0  || NewSample > 127) ? CurrentSample : NewSample; 
        }

        public override void Reset()
        {
            base.Reset();
            LoadedSample = -1;
            byteIndex = -1;
            bitIndex = 0;
            m_samplePitch = 0xB;
        }
