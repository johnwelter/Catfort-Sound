        public readonly int[] timerLut =
        {
            428, 380, 340, 320, 286, 254, 226, 214, 190, 160, 142, 128, 106, 84, 72, 54
        };

        public DMC()
        {
            SampleList.Add(EB0_Snare);
            SampleList.Add(EB0_Kick);
        }
        public virtual void SetSample(int sample, int pitch)
        {
            //m_pitch = pitch;
            //Effects.ResetEffects();
            //timer = 0;
            byteIndex = 0;
            bitIndex = 0;
            LoadedSample = sample;
            m_samplePitch = pitch;
            CurrentSample = 0;
        }

        public override float GenerateSample()
        {

            //for a given sample - get the current bit from the current byte
            //inc sample if 1, dec if 0
            //clamp between 127 and -127
            if(byteIndex == -1)
            {
                return 0;
            }
            Clock(APUConstants.CPU_CLOCKS_PER_SAMPLE, timerLut[m_samplePitch]);
            return CurrentSample * 10f;
        }

        public override void UpdateCurrentSample(int updateTicks)
        {
            byte[] dmc = SampleList[(int)LoadedSample];

            int step = ((dmc[byteIndex] >> bitIndex) & 1) == 1 ? 1 : -1;

            bitIndex += updateTicks;
            if (bitIndex >= 8)
            {
                bitIndex %= 8;
                byteIndex++;
                if (byteIndex >= dmc.Length)
                {
                    byteIndex = -1;
                }
            }

            CurrentSample = (Math.Clamp(CurrentSample + step, -127, 127));
        }
