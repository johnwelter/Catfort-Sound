    0x30, 0x30, 0x2E, 0x2D, 0x2D, 0x2B, 0x2E, 0x2D, 0x24, 0x20, 0x1A, 0x1D, 0x37, 0x1E, 0x20,
    0x23, 0x23, 0x2B, 0x33, 0x39, 0x3F, 0x3F, 0x36, 0x30, 0x2B, 0x2E, 0x34, 0x39, 0x34, 0x27, 0x14,
    0x02,
};

        readonly byte[] NNMJ_FluteA = {
    0x00, 0x01, 0x0C, 0x16, 0x20, 0x24, 0x27, 0x27, 0x2A, 0x2F, 0x2F, 0x32, 0x30, 0x33, 0x36, 0x3A, 0x36,
