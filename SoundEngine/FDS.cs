{
    class FDS : Channel
    {
        public enum Samples
        {
            kNNMJ_Shamisen = 0,
            kNNMJ_FluteA = 1
        }

        Samples LoadedSample = Samples.kNNMJ_Shamisen;

        private int byteIndex = 0;

        public List<byte[]> SampleList = new List<byte[]>();

        readonly byte[] NNMJ_Shamisen = {
    0x00, 0x02, 0x14, 0x27, 0x34, 0x39, 0x34, 0x2E, 0x2B, 0x30, 0x36, 0x3F, 0x3F, 0x39, 0x33, 0x2B,
